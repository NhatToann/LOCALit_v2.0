'use client'

import { useEffect, useState } from 'react'

/**
 * LOCALit Da Nang Backdrop — full-bleed photography behind every page.
 *
 * Per web-ai-slop §1a anchor #1, the page should feel rooted in Da Nang
 * itself. A single rotating photo (Han River, Marble Mountains, My Khe,
 * Son Tra, Hoài An lanterns, Ba Na Hills, Dragon Bridge…) sits BEHIND
 * the page chrome; card surfaces use `.bg-paper` so the photo shows
 * through. ONE brand teal wash (~30% multiply) keeps the photo readable
 * while carrying the 2-role identity.
 *
 * LOCAL ASSETS (2026-10-23)
 * ------------------------
 * The photos used to be hard-coded Unsplash CDN URLs. Four of the nine
 * photo IDs were deleted upstream, and the FIRST one — the index every
 * fresh guest session renders, because SSR always starts at 0 — was one
 * of the dead ones. Result: guests saw a flat white page, while
 * signed-in users (whose sessionStorage held a different index) saw a
 * photo. The dead URL also 404'd in the homepage hero preload.
 *
 * The photos now live in the repo under `public/photos/` and are
 * generated by `scripts/build-backdrop-photos.mjs`:
 *
 *   public/photos/desktop/<name>.jpg  1920x1080  (16:9)
 *   public/photos/tablet/<name>.jpg   1024x768   (4:3)
 *   public/photos/mobile/<name>.jpg    720x720   (1:1)
 *
 * Benefits over the CDN: no third-party origin (so no ORB block and no
 * third-party cookie concerns), no 404 rot, no external latency, and the
 * image ships on the same connection as the rest of the site.
 *
 * RESPONSIVE IMAGE STRATEGY
 * The same photo is served at three widths via a `<picture>` element so
 * a 375x667 phone never downloads a 1920px landscape JPEG and over-fetches
 * 4x its bandwidth budget:
 *   <640px  -> 720px square crop
 *   <1024px -> 1024px 4:3 crop
 *   ≥1024px -> 1920px 16:9 full bleed
 * `object-fit: cover` keeps the focal point centered regardless of aspect.
 *
 * The previous "extra overlay layers" (a second teal screen, two amber
 * corner blocks, a paper wash, a bottom-fade strip) were removed in the
 * 2026-10-20 cleanup because they were decorative corporate slabs. The
 * backdrop is now the photo + ONE 30% teal multiply + the per-photo
 * attribution badge.
 */
type Photo = {
  /** Stable key — used for the sessionStorage rotation index. */
  id: string
  /** File basename (no extension) inside public/photos/<size>/. */
  base: string
  /** Where the photo was taken — shown in the corner badge. */
  place: string
  /** Alt text. The img is aria-hidden, but the copy is reused by the
   *  homepage hero preload and should still describe the scene. */
  alt: string
}

/**
 * The Da Nang photo set. Filenames map to files in public/photos/.
 * Add a new photo by dropping the original in public/photos/originals/,
 * running `node scripts/build-backdrop-photos.mjs`, then adding an entry
 * here.
 */
const PHOTOS: Photo[] = [
  {
    id: 'han-river',
    base: 'han-river',
    place: 'Han River',
    alt: 'Dragon Bridge and the Han River night skyline in Da Nang',
  },
  {
    id: 'my-khe-beach',
    base: 'my-khe-beach',
    place: 'My Khe Beach',
    alt: 'My Khe Beach with the Son Tra peninsula and the beachfront highrises behind it',
  },
  {
    id: 'dragon-bridge',
    base: 'dragon-bridge',
    place: 'Dragon Bridge',
    alt: 'Dragon Bridge lit up at night in Da Nang',
  },
  {
    id: 'marble-mountains',
    base: 'marble-mountains',
    place: 'Marble Mountains',
    alt: 'Limestone peaks of the Marble Mountains near Da Nang',
  },
]

const STORAGE_KEY = 'localit-backdrop-idx'
const STORAGE_TS = 'localit-backdrop-ts'

/**
 * Pick a RANDOM photo, but never the same one twice in a row — the
 * previous index is remembered for 30 minutes, so a page reload keeps
 * the same photo (no jarring flash) while a fresh session gets
 * something new. SSR uses index 0 to avoid hydration mismatch.
 */
function pickIndexClient(): number {
  if (typeof window === 'undefined') return 0

  const stored = safeRead(STORAGE_KEY)
  const lastTs = Number(safeRead(STORAGE_TS) ?? '0')
  const prev = stored !== null ? parseInt(stored, 10) : NaN
  const hasPrev = !Number.isNaN(prev) && prev >= 0 && prev < PHOTOS.length

  // Within the freshness window, keep showing the current photo.
  if (hasPrev && Date.now() - lastTs < 30 * 60 * 1000) {
    return prev
  }

  // Otherwise pick at random, avoiding an immediate repeat.
  let next = Math.floor(Math.random() * PHOTOS.length)
  if (hasPrev && PHOTOS.length > 1 && next === prev) {
    next = (next + 1) % PHOTOS.length
  }

  try {
    window.sessionStorage.setItem(STORAGE_KEY, String(next))
    window.sessionStorage.setItem(STORAGE_TS, String(Date.now()))
  } catch {
    /* ignore — private mode */
  }
  return next
}

/** sessionStorage reads throw in private mode — never let that break render. */
function safeRead(key: string): string | null {
  try {
    return window.sessionStorage.getItem(key)
  } catch {
    return null
  }
}

export default function DaNangBackdrop() {
  const [index, setIndex] = useState(0)

  useEffect(() => {
    setIndex(pickIndexClient())
  }, [])

  const photo = PHOTOS[index]
  // Treat <640px as mobile. The Tailwind sm: breakpoint (=640px) marks the
  // tablet-vs-mobile division in the rest of the codebase; tablet extends
  // up to lg: (=1024px). Single source of truth in one matchMedia call so
  // we don't pick a different breakpoint per consumer.
  const imgClass = 'absolute inset-0 w-full h-full object-cover'

  return (
    <div aria-hidden="true" className="fixed inset-0 -z-10 overflow-hidden bg-paper">
      {/* Responsive photo via <picture>. Three sources ordered smallest-to-
          largest so the browser picks the FIRST that matches (mobile-first).
          The <img> fallback is the desktop full-bleed JPEG. */}
      <picture>
        <source media="(max-width: 639px)" srcSet={`/photos/mobile/${photo.base}.jpg`} />
        <source media="(max-width: 1023px)" srcSet={`/photos/tablet/${photo.base}.jpg`} />
        <img
          src={`/photos/desktop/${photo.base}.jpg`}
          alt={photo.alt}
          className={imgClass}
          loading="eager"
          decoding="async"
          fetchPriority="high"
          style={{
            filter: 'saturate(1.2) contrast(1.08) brightness(0.92)',
          }}
        />
      </picture>

      {/* Brand wash — single solid teal multiplied over the photo. ONE
          color, no gradient. Removed on 2026-10-20: the second teal
          `mixBlendMode: screen` layer, the amber corner blocks top-right
          + bottom-left, the paper wash, and the bottom-fade strip — see
          the 2026-10-20 commit message for the rationale. */}
      <div
        className="absolute inset-0"
        style={{
          backgroundColor: 'rgba(15, 118, 110, 0.30)',
          mixBlendMode: 'multiply',
        }}
      />

      {/* Tiny attribution mark, bottom-right, never visible to assistive tech */}
      <span className="absolute bottom-2 right-3 text-[10px] text-white font-semibold tracking-wider uppercase pointer-events-none select-none bg-ink/70 px-2 py-0.5 rounded-sm">
        {photo.place}
      </span>
    </div>
  )
}

export { PHOTOS as BACKDROP_PHOTOS }
