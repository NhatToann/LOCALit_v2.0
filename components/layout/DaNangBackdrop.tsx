'use client'

import { useEffect, useState } from 'react'
import { BACKDROP_PHOTOS, type Photo } from '@/lib/photos'

/**
 * LOCALit Da Nang Backdrop — full-bleed photography behind every page.
 *
 * Per web-ai-slop §1a anchor #1, the page should feel rooted in Da Nang
 * itself. A single rotating photo sits BEHIND the page chrome; card
 * surfaces use `.bg-paper` so the photo shows through.
 *
 * LOCAL ASSETS (2026-10-23)
 * ------------------------
 * The photos used to be hard-coded Unsplash CDN URLs. Four of the nine
 * photo IDs were deleted upstream, and the FIRST one — the index every
 * fresh guest session renders, because SSR always starts at 0 — was one
 * of the dead ones. Result: guests saw a flat white page, while
 * signed-in users (whose sessionStorage held a different index) saw a
 * photo. The dead URL also 404'd in the homepage hero preload.
 *
 * The photos now live in the repo under `public/photos/` and are
 * generated by `scripts/build-backdrop-photos.mjs`. The shared list
 * lives in `lib/photos.ts` so the hero and the backdrop can never
 * disagree about a filename.
 *
 * RESPONSIVE IMAGE STRATEGY
 * The same photo is served at three widths via a `<picture>` element so
 * a 375x667 phone never downloads a 1920px landscape JPEG:
 *   <640px  -> 720px square crop
 *   <1024px -> 1024px 4:3 crop
 *   ≥1024px -> 1920px 16:9 full bleed
 *
 * LAYERING (2026-10-23)
 * ---------------------
 * The backdrop must be the LAST painted layer, sitting behind every
 * piece of page content. Two things were fighting it:
 *
 *  1. `body` had `background-color: var(--color-paper)` (opaque
 *     #FFFFFF). A `z-index: -10` element still paints behind its
 *     parent's background, so the photo was being covered by an
 *     opaque white rectangle. The fix: `body` and `html` now have a
 *     TRANSPARENT background, and the paper tone is painted by the
 *     backdrop's own base layer instead.
 *
 *  2. The hero on `/` is a full-bleed photo of its own. When the
 *     backdrop picked the same scene, the same bridge appeared twice
 *     on one screen. The backdrop now excludes the hero's photo from
 *     its rotation.
 */
const STORAGE_KEY = 'localit-backdrop-idx'
const STORAGE_TS = 'localit-backdrop-ts'

/**
 * Photos eligible for the backdrop rotation.
 *
 * The hero's LANDMARK is excluded, not just its filename. Two different
 * files can show the same subject — the Dragon Bridge at night, and
 * the Han River shot that also frames it — so filtering by filename
 * alone would still put the same scene twice on one page. Comparing
 * the `landmark` field is what actually prevents that.
 *
 * When the pool holds only ONE photo there is nothing left for the
 * backdrop once the hero has taken it, so `BACKDROP_PHOTOS` (in
 * `lib/photos.ts`) hands the single photo to the backdrop and the
 * hero falls back to a solid brand teal.
 */
const ROTATION_PHOTOS: Photo[] = BACKDROP_PHOTOS

/**
 * Pick a RANDOM photo, but never the same one twice in a row — the
 * previous index is remembered for 30 minutes, so a page reload keeps
 * the same photo (no jarring flash) while a fresh session gets
 * something new. SSR uses index 0 to avoid hydration mismatch.
 */
function pickIndexClient(): number {
  if (typeof window === 'undefined') return 0

  const stored = safeRead(STORAGE_KEY)
  const lastTs = Number(safeRead(STORAGE_TS) ?? '0')
  const prev = stored !== null ? parseInt(stored, 10) : NaN
  const hasPrev = !Number.isNaN(prev) && prev >= 0 && prev < ROTATION_PHOTOS.length

  // Within the freshness window, keep showing the current photo.
  if (hasPrev && Date.now() - lastTs < 30 * 60 * 1000) {
    return prev
  }

  // Otherwise pick at random, avoiding an immediate repeat.
  let next = Math.floor(Math.random() * ROTATION_PHOTOS.length)
  if (hasPrev && ROTATION_PHOTOS.length > 1 && next === prev) {
    next = (next + 1) % ROTATION_PHOTOS.length
  }

  try {
    window.sessionStorage.setItem(STORAGE_KEY, String(next))
    window.sessionStorage.setItem(STORAGE_TS, String(Date.now()))
  } catch {
    /* ignore — private mode */
  }
  return next
}

/** sessionStorage reads throw in private mode — never let that break render. */
function safeRead(key: string): string | null {
  try {
    return window.sessionStorage.getItem(key)
  } catch {
    return null
  }
}

export default function DaNangBackdrop() {
  const [index, setIndex] = useState(0)

  useEffect(() => {
    setIndex(pickIndexClient())
  }, [])

  const photo = ROTATION_PHOTOS[index] ?? ROTATION_PHOTOS[0]
  const imgClass = 'absolute inset-0 w-full h-full object-cover'

  return (
    <div aria-hidden="true" className="fixed inset-0 -z-10 overflow-hidden">
      {/* Paper base. This is the opaque layer that gives the page its
          off-white Da Nang-print tone. It sits INSIDE the backdrop
          (rather than on <body>) so the photo can paint over it. */}
      <div className="absolute inset-0 bg-paper" />

      {/* Responsive photo via <picture>. Three sources ordered smallest-to-
          largest so the browser picks the FIRST that matches (mobile-first).
          The <img> fallback is the desktop full-bleed crop. */}
      {photo && (
        <picture>
          <source media="(max-width: 639px)" srcSet={`/photos/mobile/${photo.base}.webp`} />
          <source media="(max-width: 1023px)" srcSet={`/photos/tablet/${photo.base}.webp`} />
          <img
            src={`/photos/desktop/${photo.base}.webp`}
            alt={photo.alt}
            className={imgClass}
            loading="eager"
            decoding="async"
            fetchPriority="high"
            style={{
              // The backdrop is a TEXTURE, not a feature — it must stay
              // quiet enough that no content competes with it, but it
              // still has to be VISIBLE. The photo is desaturated and
              // lightened toward the paper tone, then the wash below
              // pulls it toward the brand teal.
              filter: 'saturate(0.45) contrast(0.95) brightness(1.06)',
              opacity: 0.24,
            }}
          />
        </picture>
      )}

      {/* Brand wash — a single solid teal multiplied over the photo. ONE
          color, no gradient. Removed on 2026-10-20: the second teal
          `mixBlendMode: screen` layer, the amber corner blocks top-right
          + bottom-left, the paper wash, and the bottom-fade strip — see
          the 2026-10-20 commit message for the rationale. */}
      <div
        className="absolute inset-0"
        style={{
          backgroundColor: 'rgba(15, 118, 110, 0.12)',
          mixBlendMode: 'multiply',
        }}
      />
    </div>
  )
}
